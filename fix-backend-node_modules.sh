#!/bin/bash
# Run this from inside your local Annie-Adrena-Portfolio-Site-Backend repo folder.
# Removes the committed (and partially broken) node_modules from git tracking,
# so Vercel does a clean npm install on the next deploy instead of using
# the corrupted copy that's currently in the repo.

set -e

# Stop tracking node_modules (keeps the files on disk locally, just untracks them)
git rm -r --cached node_modules

# .gitignore already has "node_modules/" in it, but confirm just in case:
grep -qxF "node_modules/" .gitignore || echo "node_modules/" >> .gitignore

git add .gitignore
git commit -m "Stop tracking node_modules; let Vercel install dependencies fresh"
git push

echo "Done. Push triggers a new Vercel deploy with a clean npm install."
